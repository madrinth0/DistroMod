"""Input validation used across DistroMod.

All user supplied values (theme names, font names, file paths) pass through
these helpers before they are used to build file system paths or shell
commands.  This prevents path traversal, injection and obvious misuse.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Optional, Union

_MAX_NAME_LENGTH = 128
# Control characters are never valid in a name we accept.
_CONTROL_RE = re.compile(r"[\x00-\x1f\x7f]")


def validate_theme_name(name: str, what: str = "name") -> str:
    """Validate a theme, icon, cursor or font name.

    The value must be a non-empty identifier that contains no path separators,
    no control characters and is not a relative-path special (``.`` / ``..``).

    Args:
        name: Value to validate.
        what: Human readable label used in error messages.

    Returns:
        The stripped, validated value.

    Raises:
        ValueError: If the value is not acceptable.
    """
    if not isinstance(name, str):
        raise ValueError(f"{what.capitalize()} must be a string")
    value = name.strip()
    if not value:
        raise ValueError(f"{what.capitalize()} cannot be empty")
    if len(value) > _MAX_NAME_LENGTH:
        raise ValueError(f"{what.capitalize()} is too long (max {_MAX_NAME_LENGTH} characters)")
    if _CONTROL_RE.search(value):
        raise ValueError(f"{what.capitalize()} contains control characters")
    if "/" in value or "\\" in value:
        raise ValueError(f"{what.capitalize()} cannot contain path separators")
    if value in {".", ".."}:
        raise ValueError(f"Invalid {what}: {value!r}")
    if value.startswith("-"):
        raise ValueError(f"{what.capitalize()} cannot start with '-'")
    return value


def validate_path(
    path: Union[str, os.PathLike],
    must_exist: bool = False,
    kind: str = "file",
    allow_create_parent: bool = False,
) -> str:
    """Validate and normalise a user supplied file system path.

    Args:
        path: Path to validate. ``~`` and environment variables are expanded.
        must_exist: When ``True`` the path must already exist and be readable.
        kind: ``"file"`` (default) or ``"dir"`` - enforced when it exists.
        allow_create_parent: When ``True`` and ``must_exist`` is ``False``,
            missing parent directories are created.

    Returns:
        The absolute, normalised path as a string.

    Raises:
        ValueError: If the path is malformed or fails the requested checks.
        PermissionError: If the path exists but is not readable, or its parent
            is not writable for write operations.
    """
    if isinstance(path, os.PathLike):
        path = os.fspath(path)
    if not isinstance(path, str):
        raise ValueError("Path must be a string")
    raw = path.strip()
    if not raw:
        raise ValueError("Path cannot be empty")
    if "\x00" in raw:
        raise ValueError("Path contains a null byte")

    resolved = Path(raw).expanduser()
    if not resolved.is_absolute():
        resolved = Path.cwd() / resolved
    resolved = Path(os.path.normpath(str(resolved)))

    if must_exist:
        if not resolved.exists():
            raise ValueError(f"Path does not exist: {resolved}")
        if kind == "file" and resolved.is_dir():
            raise ValueError(f"Expected a file but found a directory: {resolved}")
        if kind == "dir" and not resolved.is_dir():
            raise ValueError(f"Expected a directory: {resolved}")
        if kind == "file" and not os.access(resolved, os.R_OK):
            raise PermissionError(f"Path is not readable: {resolved}")
    else:
        parent = resolved.parent
        if not parent.exists():
            if allow_create_parent:
                try:
                    parent.mkdir(parents=True, exist_ok=True)
                except OSError as exc:
                    raise ValueError(f"Cannot create parent directory {parent}: {exc}") from exc
            else:
                raise ValueError(f"Parent directory does not exist: {parent}")
        if not os.access(parent, os.W_OK):
            raise PermissionError(f"Parent directory is not writable: {parent}")

    return str(resolved)


def validate_backup_id(backup_id: str) -> str:
    """Validate a backup identifier.

    IDs are generated by DistroMod and only ever contain safe characters, so a
    value containing a separator or ``..`` is rejected to prevent traversal.
    """
    if not isinstance(backup_id, str):
        raise ValueError("Backup ID must be a string")
    value = backup_id.strip()
    if not value:
        raise ValueError("Backup ID cannot be empty")
    if value in {".", ".."}:
        raise ValueError(f"Invalid backup ID: {value!r}")
    if "/" in value or "\\" in value or "\x00" in value:
        raise ValueError("Backup ID contains illegal characters")
    if not re.fullmatch(r"[A-Za-z0-9._-]+", value):
        raise ValueError("Backup ID contains illegal characters")
    return value


def validate_font_size(size: Optional[int], minimum: int = 6, maximum: int = 72) -> Optional[int]:
    """Validate an optional font size."""
    if size is None:
        return None
    if isinstance(size, bool) or not isinstance(size, int):
        try:
            size = int(size)
        except (TypeError, ValueError):
            raise ValueError("Font size must be an integer") from None
    if size < minimum or size > maximum:
        raise ValueError(f"Font size must be between {minimum} and {maximum}")
    return size
